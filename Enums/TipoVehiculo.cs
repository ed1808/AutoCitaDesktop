        /// Motocicleta.
        /// </summary>
        Moto = 1,

        /// <summary>
        /// Automóvil (vehículo de pasajeros liviano).
        /// </summary>
        Automovil = 2,

        /// <summary>
        /// Camioneta (vehículo utilitario mediano).
        /// </summary>
        Camioneta = 3,

        /// <summary>
        /// Camión (vehículo de carga pesado).
        /// </summary>
        Camion = 4
    }
}
